import assert from 'node:assert/strict';
import {Window} from 'happy-dom';
import {pathToFileURL} from 'node:url';
import {readdirSync} from 'node:fs';
import path from 'node:path';
const output = process.argv[2] ?? 'local-baseline/v180-scenic-compare';
const win = new Window({url:`https://example.test/${path.basename(output)}/#/components/slider`, width:390, height:844, settings:{disableJavaScriptFileLoading:true,disableCSSFileLoading:true,disableIframePageLoading:true}});
for (const key of ['window','document','navigator','location','history','localStorage','sessionStorage','HTMLElement','HTMLDialogElement','HTMLInputElement','SVGElement','Element','Node','Event','MouseEvent','PointerEvent','KeyboardEvent','MutationObserver','ResizeObserver','IntersectionObserver','Image','CSS','DOMRect','getComputedStyle','matchMedia','requestAnimationFrame','cancelAnimationFrame']) {
 const value = key==='window'?win:key==='getComputedStyle'||key==='matchMedia'||key.endsWith('AnimationFrame')?win[key].bind(win):win[key];
 Object.defineProperty(globalThis,key,{value,writable:true,configurable:true});
}
win.document.body.innerHTML='<div id="app"></div>';
const js=readdirSync(output+'/assets').find(p=>p.startsWith('components-')&&p.endsWith('.js'));
await import(pathToFileURL(path.resolve(output,'assets',js)).href);
const tick=async()=>{await new Promise(r=>setTimeout(r,60))};
await tick();
const document=win.document;
const study=document.querySelector('.ab-study');
assert.ok(study,'stable #/components/slider deep link mounts comparison');
const surface=study.querySelector('.ab-comparison');
const control=study.querySelector('input[aria-label="Comparison split"]');
const original=study.querySelector('.ab-original');
let width=274;
surface.getBoundingClientRect=()=>new win.DOMRect(46,20,width,width*2/3);
const split=()=>Number(control.value);
assert.equal(control.type,'range');
assert.equal(study.querySelectorAll('input[aria-label="Comparison split"]').length,1);
assert.equal(split(),50);
assert.equal(original.style.clipPath,'inset(0 50% 0 0)');
assert.equal(surface.querySelector('img').getAttribute('src'),'assets/nature-alpine-768.webp');
assert.match(surface.querySelector('img').srcset,/384w.*768w.*1536w/);
const captures=[];
surface.setPointerCapture=id=>captures.push(id);
const pointer=async (name,clientX,clientY,{id=1,pointerType='mouse',isPrimary=true,button=0}={})=>{
 surface.dispatchEvent(new win.PointerEvent(name,{clientX,clientY,pointerType,isPrimary,pointerId:id,button,bubbles:true,cancelable:true}));
 await tick();
};
const key=async key=>{
 const event=new win.KeyboardEvent('keydown',{key,bubbles:true,cancelable:true});
 control.dispatchEvent(event);
 await tick();
 assert.equal(event.defaultPrevented,true);
};
await pointer('pointerdown',46+width*.7,80);
assert.equal(split(),70);
assert.equal(document.activeElement,control);
assert.deepEqual(captures,[1]);
await pointer('pointermove',46+width*.92,84);
assert.equal(split(),92);
await pointer('pointerup',46+width*.94,84);
assert.equal(split(),94);
assert.equal(original.style.clipPath,'inset(0 6% 0 0)');
await pointer('pointermove',46+width*.5,84);
assert.equal(split(),94,'no movement after release');
await key('Home');
assert.equal(split(),0);
assert.equal(control.getAttribute('aria-valuetext'),'Adjusted photo only');
await key('ArrowRight');
assert.equal(split(),1);
await key('PageUp');
assert.equal(split(),11);
await key('End');
assert.equal(split(),100);
assert.equal(control.getAttribute('aria-valuetext'),'Original photo only');
await key('ArrowLeft');
assert.equal(split(),99);
width=205;
const touch={id:2,pointerType:'touch'};
await pointer('pointerdown',70,90,touch);
assert.equal(split(),99,'touch waits to determine intent');
await pointer('pointermove',73,113,touch);
await pointer('pointermove',150,134,touch);
await pointer('pointercancel',152,136,touch);
assert.equal(split(),99,'vertical scroll gesture does not move comparison');
await pointer('pointerdown',70,90,touch);
await pointer('pointermove',46+width*.35,94,touch);
assert.equal(split(),35);
await pointer('pointermove',46+width*.43,95,{id:6,pointerType:'touch',isPrimary:false});
assert.equal(split(),35,'other finger cannot override');
await pointer('lostpointercapture',80,95,touch);
await pointer('pointermove',46+width*.6,96,touch);
assert.equal(split(),35,'lost capture ends the gesture');
await pointer('pointerdown',46+width*.45,92,touch);
await pointer('pointerup',46+width*.45,92,touch);
assert.equal(split(),45,'tap positions the comparison without requiring a drag');
await pointer('pointerdown',225,92,{button:2});
assert.equal(split(),45,'context click does not move comparison');
assert.match(study.querySelector('.ab-footer').textContent,/75% brightness/);
const reset=[...study.querySelectorAll('button')].find(x=>x.textContent.includes('Reset brightness'));
assert.ok(reset);
reset.click();
await tick();
assert.match(study.querySelector('.ab-footer').textContent,/100% brightness/);
assert.equal(surface.querySelector('img').style.filter,'brightness(1)');
assert.equal(split(),45,'brightness independent from split');
console.log('Built gallery mount: exact deep link, photo sources, mouse drag/focus, keyboard endpoints, independent brightness, touch pan/cancel/tap and capture lifecycle checked. No real-browser claims.');
await win.happyDOM.close();
