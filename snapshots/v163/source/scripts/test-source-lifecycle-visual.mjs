import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
const source=await readFile(new URL('../apps/storybook/vesper/site/ToolFeedbackStudies.tsx',import.meta.url),'utf8');
const css=await readFile(new URL('../apps/storybook/vesper/site/tool-feedback-studies.css',import.meta.url),'utf8');
const pure=source.slice(source.indexOf("type Phase="),source.indexOf('function EvidenceSource'));
const {code}=await transform(pure,{loader:'ts',format:'esm'});
const {initialBatch,batchReducer,sourceState}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
let s=initialBatch;
assert.equal(sourceState(s,'notes'),'waiting');
s=batchReducer(s,{type:'start'});
assert.equal(sourceState(s,'notes'),'reading');
assert.equal(sourceState(s,'metrics'),'reading');
s=batchReducer(s,{type:'notes',run:s.run});
assert.equal(sourceState(s,'notes'),'ready');
assert.equal(sourceState(s,'metrics'),'reading');
s=batchReducer(s,{type:'finish',run:s.run});
assert.equal(sourceState(s,'metrics'),'unavailable');
s=batchReducer(s,{type:'retry'});
assert.equal(sourceState(s,'notes'),'ready','retry must not animate completed notes');
assert.equal(sourceState(s,'metrics'),'reading');
const old=s.run;
s=batchReducer(s,{type:'stop'});
assert.equal(sourceState(s,'metrics'),'stopped');
assert.equal(sourceState(s,'notes'),'ready');
assert.deepEqual(batchReducer(s,{type:'finish',run:old}),s,'late results ignored');
s=batchReducer(initialBatch,{type:'start'});
s=batchReducer(s,{type:'finish',run:s.run});
s=batchReducer(s,{type:'retry'});
s=batchReducer(s,{type:'finish',run:s.run});
assert.equal(sourceState(s,'metrics'),'ready');
assert.equal(Number(s.notes)+Number(s.metrics),2);
assert.match(source,/className="tf-source-signal"[^>]*aria-hidden="true"/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(css,/data-state=ready\] \.tf-source-signal path\{stroke-dasharray:none/);
assert.match(css,/@media\(forced-colors:active\)/);
console.log('Source lifecycle: waiting/read/partial/retry/stop/complete and motion contracts pass.');
